"""Deterministic approved-preview -> RGB332 ROM conversion and shared arena map.

Run --write once to generate active assets; --check verifies without changing them.
Only 24x24 native approved inputs are sampled; FF is reserved for transparency.
The preserved collision masks are separate from all visual alpha channels.
Requires Pillow. Historical build_jungle_assets.py is for Phase 3A, not this phase.
"""
import argparse
import json
import math
import subprocess
import statistics
import sys
from collections import Counter, deque
from pathlib import Path

from PIL import Image, ImageFilter
sys.dont_write_bytecode=True
from build_jungle_assets import parse_mif, rgb

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/jungle/implemented'
V2 = ROOT / 'assets/jungle/previews_v2'
V3 = ROOT / 'assets/jungle/previews_v3_relics'
PILLARS = {(11,4),(6,7),(17,8),(11,15),(3,14),(18,14)}
BLOCKS = PILLARS | {(2,3),(3,3),(4,3),(5,3),(2,4),(2,5),
    (14,3),(15,3),(16,3),(17,3),(17,4),(17,5),
    (3,9),(3,10),(4,10),(14,11),(15,11),(16,11),(16,12),(16,13),
    (6,15),(7,15),(8,15),(6,14)}
TILES = ['floor_base_24','grass_tile_24','stone_tile_24','floor_carved_24',
         'rock_tile_24','ruin_wall_24','ruin_pillar_24']
SOURCES = dict(zip(TILES, ['floor_base_24','floor_mossy_24','floor_cracked_24',
    'floor_carved_24','ruin_block_24','ruin_wall_24','ruin_pillar_24']))
SOURCES.update(snake_head_24='snake_head_up_24',snake_body_24='snake_body_24',
    red_apple_24='ruby_relic_24',blue_apple_24='sapphire_relic_24',black_apple_24='cursed_relic_24')

def patch(c,r,cx,cy,sx,sy):
    return math.exp(-((c-cx)/sx)**2-((r-cy)/sy)**2)

def arena_map():
    remaining = {(c,r) for r in range(18) for c in range(20)} - BLOCKS
    floors = {}
    def assign(kind,n,score):
        for p in sorted(remaining,key=lambda p:(score(*p),p),reverse=True)[:n]:
            floors[p] = kind
            remaining.remove(p)
    assign(1,75,lambda c,r:patch(c,r,1,2,4,4)+patch(c,r,18,14,4,5)+.8*patch(c,r,5,16,3,3))
    assign(2,57,lambda c,r:patch(c,r,15,5,3,4)+patch(c,r,4,10,3,3)+.5*patch(c,r,12,15,4,2))
    assign(3,24,lambda c,r:math.sin(c*1.7+r*.7)+math.cos(r*1.4-c*.3)-.1*patch(c,r,10,9,3,3))
    for p in remaining: floors[p] = 0
    result = []
    for r in range(18):
        for c in range(20):
            if (c,r) in BLOCKS:
                kind = 6 if (c,r) in PILLARS else 5 if ((c-1,r) in BLOCKS or (c+1,r) in BLOCKS) else 4
                rot = 0
            else:
                kind = floors[c,r]
                rot = (c*7+r*11+c*r)%4 if kind==2 else (c//5+2*(r//6))%4 if kind==1 else 0
            result.append((rot<<3)|kind)
    assert Counter(floors.values()) == {0:174,1:75,2:57,3:24}
    assert len(BLOCKS)==30 and not any((c,r) in BLOCKS for r in range(7,12) for c in range(8,13))
    for p in [(7,3),(5,10),(12,6)]: assert p not in BLOCKS
    reached={(10,9)}; queue=deque(reached)
    while queue:
        c,r=queue.popleft()
        for p in [(c-1,r),(c+1,r),(c,r-1),(c,r+1)]:
            if 0<=p[0]<20 and 0<=p[1]<18 and p not in BLOCKS and p not in reached:
                reached.add(p); queue.append(p)
    assert len(reached)==330
    return result

def map_include(mapping):
    rows=[]; rocks=[]
    for r in range(18):
        row=sum(mapping[r*20+c]<<(c*5) for c in range(20))
        mask=sum(1<<c for c in range(20) if (c,r) in BLOCKS)
        rows.append(f"        5'd{r}: row = 100'h{row:025X};")
        rocks.append(f"        5'd{r}: jungleRockRow = 20'h{mask:05X};")
    return '// Generated by scripts/implement_jungle_preview.py; edit the source map, not this table.\n' + '''// Tile descriptor: [4:3] clockwise quarter-turns, [2:0] tile ROM kind.
function automatic [4:0] jungleTile(input logic [4:0] x, y);
    logic [99:0] row;
    begin
        case (y)
'''+'\n'.join(rows)+'''
        default: row = 100'd0;
        endcase
        jungleTile = (x < 20 && y < 18) ? (row >> (x * 5)) : 5'd0;
    end
endfunction
function automatic [19:0] jungleRockRow(input logic [4:0] y);
    begin
        case (y)
'''+'\n'.join(rocks)+'''
        default: jungleRockRow = 20'd0;
        endcase
    end
endfunction
'''

def mif(values,width=8):
    return f'WIDTH={width};\nDEPTH={len(values)};\nADDRESS_RADIX=HEX;\nDATA_RADIX=HEX;\nCONTENT BEGIN\n' + ''.join(f'{i:03X} : {v:02X};\n' for i,v in enumerate(values)) + 'END;\n'

def image(values):
    im=Image.new('RGBA',(24,24)); im.putdata([(*rgb(v),0 if v==255 else 255) for v in values]); return im

def converted(name):
    folder = V3 if 'apple' in name else V2
    im=Image.open(folder/(SOURCES[name]+'.png')).convert('RGBA')
    assert im.size==(24,24)
    if name in TILES[:2]: im=im.filter(ImageFilter.MedianFilter(3))
    palette = [0x00,0x04,0x24,0x28] if name in TILES[:4] else [0x00,0x04,0x24,0x28,0x49,0x6D,0x91,0xAD] if name in TILES[4:] else range(255)
    pixels=list(im.get_flattened_data())
    median=statistics.median(sum(p[:3])/3 for p in pixels)
    values=[]
    for p in pixels:
        if p[3]<128:
            values.append(0x24 if name in TILES else 255)
        else:
            candidates=palette
            if name.startswith('snake_') and p[1]>p[0]*1.2:
                # Keep emerald shades emerald rather than cyan after the coarse
                # two-bit blue conversion; cream eyes/gold accents use all codes.
                candidates=[v for v in range(255) if (v&3)==0]
            values.append(min(candidates,key=lambda v:sum((a-b)**2 for a,b in zip(p[:3],rgb(v)))))
    if name in TILES[:4]:
        # Content-adaptive dark olive ramp avoids the blue/olive speckling of
        # naive RGB332 nearest-color conversion. Preserve the source's dark
        # cracks/engraving and connected greener moss, not tiny color noise.
        values=[0x04 if sum(p[:3])/3 < median-(3 if name=='floor_carved_24' else 4 if name=='stone_tile_24' else 7)
                else 0x28 if name=='grass_tile_24' and p[1]-p[0]>10 else 0x24
                for p in pixels]
        q=Image.new('L',(24,24)); q.putdata(values)
        values=list((q.filter(ImageFilter.ModeFilter(3)) if name in TILES[:2] else q).get_flattened_data())
        for y in range(24):
            for x in range(24):
                if x in (0,23) or y in (0,23): values[y*24+x]=0x04
    return values

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--write',action='store_true'); ap.add_argument('--check',action='store_true'); ap.add_argument('--fixtures',action='store_true'); args=ap.parse_args()
    assert args.write or args.check or args.fixtures
    masks=json.loads((ROOT/'assets/jungle/collision_masks.json').read_text())['assets']
    roms={name:converted(name) for name in SOURCES}
    mask=lambda name:[int(b) for row in masks[name]['rows'] for b in row]
    roms['snake_head_collision_24']=[0 if b else 255 for b in mask('snake_head_24')]
    roms['relic_collision_24']=[a|(b<<1)|(c<<2) for a,b,c in zip(mask('red_apple_24'),mask('blue_apple_24'),mask('black_apple_24'))]
    mapping=arena_map()
    for name,values in roms.items():
        content=mif(values,3 if name=='relic_collision_24' else 8)
        path=ROOT/'RTL/mifs'/(name+'.mif')
        if args.write: path.write_text(content)
        if args.check: assert path.read_text()==content, str(path)
    include=ROOT/'RTL/VGA/jungle_map.svh'; content=map_include(mapping)
    if args.write: include.write_text(content)
    if args.check: assert include.read_text()==content
    if args.write:
        OUT.mkdir(parents=True,exist_ok=True)
        for name,values in roms.items():
            if 'collision' not in name:
                image(values).save(OUT/(name+'.png'))
                image(values).resize((192,192),Image.Resampling.NEAREST).save(OUT/(name+'_8x.png'))
        scene=Image.new('RGBA',(640,480),(*rgb(0x04),255))
        # Retain the approved HUD layout as a reference, not new active HUD assets.
        reference=Image.open(V3/'full_scene.png').convert('RGBA')
        hud=reference.crop((8,24,128,456))
        hud_palette=[0x04,0x8D,0xF9,0xD9,0xED,0x57,0xB3]
        hud.putdata([(*rgb(min(hud_palette,key=lambda v:sum((a-b)**2 for a,b in zip(p[:3],rgb(v))))),255) for p in hud.get_flattened_data()])
        scene.paste(hud,(8,24))
        for r in range(18):
            for c in range(20):
                desc=mapping[r*20+c]; tile=image(roms[TILES[desc&7]])
                tile=tile.rotate(-90*(desc>>3))
                scene.paste(tile,(144+24*c,24+24*r))
        # Illustrative approval pose; not a simulation/hardware framebuffer capture.
        trail=[(10,13),(10,12),(10,11),(10,10),(10,9),(10,14),(11,14),(12,14),(13,14),
               (13,13),(13,12),(13,11),(13,10),(13,9),(13,8),(13,7),(13,6),(12,6),(11,6)]
        for c,r in trail:
            sprite=image(roms['snake_body_24']); scene.alpha_composite(sprite,(144+24*c,24+24*r))
        scene.alpha_composite(image(roms['snake_head_24']),(144+24*10,24+24*9))
        for name,c,r in [('red_apple_24',7,3),('blue_apple_24',5,10),('black_apple_24',12,6)]:
            scene.alpha_composite(image(roms[name]),(144+24*c,24+24*r))
        scene.convert('RGB').save(OUT/'full_scene_rgb332.png')
        (OUT/'arena_map.json').write_text(json.dumps({'columns':20,'rows':18,'descriptor':mapping,'blocked':sorted(BLOCKS),'floor_counts':{0:174,1:75,2:57,3:24}},indent=2)+'\n')
    if args.fixtures:
        fixture=ROOT/'db/jungle_implementation_fixture'; fixture.mkdir(parents=True,exist_ok=True)
        for name,values in roms.items():
            (fixture/(name+'.hex')).write_text(''.join(f'{v:02x}\n' for v in values))
        (fixture/'map.hex').write_text(''.join(f'{v:02x}\n' for v in mapping))
        # Golden RTL remains the last verified build, independent of edited files.
        for filename,module in [('headBitMap.sv','headBitMap'),('AppleBitMap.sv','AppleBitMap'),('snake_body.sv','snake_body')]:
            raw=subprocess.check_output(['git','show','19ae76c:RTL/VGA/'+filename],cwd=ROOT).decode().replace('\r\n','\n')
            raw=raw.replace('module '+module+' (','module legacy_'+module+' (')
            for name in ['snake_head_24','snake_body_24','red_apple_24','blue_apple_24','black_apple_24']:
                raw=raw.replace('RTL/mifs/'+name+'.mif','db/jungle_implementation_fixture/legacy_'+name+'.mif')
            (fixture/('legacy_'+filename)).write_text(raw)
        for name in ['snake_head_24','snake_body_24','red_apple_24','blue_apple_24','black_apple_24']:
            raw=subprocess.check_output(['git','show','19ae76c:RTL/mifs/'+name+'.mif'],cwd=ROOT).decode()
            (fixture/('legacy_'+name+'.mif')).write_text(raw)
    print('PASS: approved inputs, RGB332/FF, separate masks, 30 obstacles, 330 connected safe cells, fixed floor mix')

if __name__=='__main__': main()
